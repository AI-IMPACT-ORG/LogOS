set -euo pipefail

OUT_DIR="${1:-}"
if [[ -z "${OUT_DIR}" ]]; then
  echo "usage: write_html_index.sh <html-dir>" >&2
  exit 2
fi

mkdir -p "${OUT_DIR}"

cat > "${OUT_DIR}/index.html" <<'EOF'
<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>LogOS (Agda) — Docs</title>
    <link rel="stylesheet" href="Agda.css" />
  </head>
  <body>
    <main style="max-width: 56rem; margin: 2rem auto; padding: 0 1rem; font-family: system-ui, -apple-system, Segoe UI, Roboto, Arial, sans-serif;">
      <h1>LogOS (Agda) — Docs</h1>
      <p>Selected entrypoints generated by Agda’s HTML backend.</p>
      <ul>
        <li><a href="docs.Core.Orientation.LogOS_Overview.html">Start here: overview</a></li>
        <li><a href="docs.Core.Spec.LogOS_Specification.html">Specification (implementation-facing)</a></li>
        <li><a href="docs.Core.Spec.LogicalTransformers.html">Spec notes (LaTeX structure tracker)</a></li>
      </ul>
    </main>
  </body>
</html>
EOF

touch "${OUT_DIR}/.nojekyll"
