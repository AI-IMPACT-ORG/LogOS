from __future__ import annotations

import os
import re
from pathlib import Path

ROOT = Path(".").resolve()
OUT = (ROOT / Path(os.environ["OUT_PATH"])).resolve()

TARGETS = {
    "LT": ROOT / "LogOS" / "LT",
    "Ports": ROOT / "LogOS" / "Ports",
}

IMPORT_RE = re.compile(r"^\s*(?:open\s+)?import\s+([A-Za-z0-9_.']+)\b")


def strip_block_comments(text: str) -> str:
    out: list[str] = []
    i = 0
    depth = 0
    while i < len(text):
        if text.startswith("{-", i):
            depth += 1
            i += 2
            continue
        if depth > 0 and text.startswith("-}", i):
            depth -= 1
            i += 2
            continue
        if depth == 0:
            out.append(text[i])
        i += 1
    return "".join(out)


def iter_imports(text: str) -> list[str]:
    clean = strip_block_comments(text)
    imports: list[str] = []
    for line in clean.splitlines():
        if "--" in line:
            line = line.split("--", 1)[0]
        if not line.strip():
            continue
        m = IMPORT_RE.match(line)
        if m:
            imports.append(m.group(1))
    return imports


def module_from_path(path: Path) -> str:
    rel = path.relative_to(ROOT)
    s = rel.as_posix()
    if not s.endswith(".agda"):
        raise ValueError(f"unexpected suffix: {rel}")
    s = s[: -len(".agda")]
    return s.replace("/", ".")


def main() -> None:
    modules: dict[str, str] = {}
    module_paths: dict[str, Path] = {}

    for layer, base in TARGETS.items():
        if not base.is_dir():
            continue
        for path in sorted(base.rglob("*.agda")):
            if "_build" in path.parts:
                continue
            name = module_from_path(path)
            modules[name] = layer
            module_paths[name] = path

    module_names = sorted(modules.keys())
    id_map = {name: f"m{i}" for i, name in enumerate(module_names)}

    edges: set[tuple[str, str]] = set()
    for name in module_names:
        path = module_paths[name]
        text = path.read_text(encoding="utf-8", errors="ignore")
        for imp in iter_imports(text):
            if imp in modules:
                edges.add((name, imp))

    edges_sorted = sorted(edges, key=lambda e: (e[0], e[1]))

    with OUT.open("w", encoding="utf-8") as f:
        f.write("<!--\n")
        f.write("LogOS: a host-minimal Agda library for modular dynamic logic systems synthesized by AI\n")
        f.write("Copyright (C) 2026 AI.IMPACT GmbH\n")
        f.write("SPDX-License-Identifier: GPL-3.0-only\n")
        f.write("-->\n\n")
        f.write("# LT/Ports Import Graph (Generated)\n\n")
        f.write("Generated by `scripts/gen/write_lt_ports_import_graph.sh`.\n\n")
        f.write("Scope: imports among modules under `LogOS/LT/**` and `LogOS/Ports/**`.\n\n")
        f.write("```mermaid\n")
        f.write("flowchart TD\n")
        for layer in ("LT", "Ports"):
            f.write(f'  subgraph "{layer}"\n')
            for name in module_names:
                if modules[name] != layer:
                    continue
                node_id = id_map[name]
                f.write(f'    {node_id}["{name}"]\n')
            f.write("  end\n")
        if edges_sorted:
            f.write("\n")
            for src, dst in edges_sorted:
                f.write(f"  {id_map[src]} --> {id_map[dst]}\n")
        f.write("```\n")

    try:
        shown = str(OUT.relative_to(ROOT))
    except ValueError:
        shown = str(OUT)
    print(f"write-lt-ports-import-graph: wrote {shown}")


if __name__ == "__main__":
    main()
PY
