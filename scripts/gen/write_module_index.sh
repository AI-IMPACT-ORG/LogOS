set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# shellcheck source=scripts/lib/check_common.sh
source "${SCRIPT_DIR}/lib/check_common.sh"

ROOT="$(check_repo_root "${BASH_SOURCE[0]}")"
cd "${ROOT}"

OUT_PATH="${1:-docs/Generated/Module_Index.md}"
OUT_DIR="$(dirname "${OUT_PATH}")"
mkdir -p "${OUT_DIR}"

OUT_PATH="${OUT_PATH}" python3 - <<'PY'
from __future__ import annotations

import os
import re
from pathlib import Path

ROOT = Path('.').resolve()
OUT = (ROOT / Path(os.environ['OUT_PATH'])).resolve()

spec_re = re.compile(r'^\s*--\s*SpecRef:\s*(.+)$')
module_re = re.compile(r'^\s*module\s+([A-Za-z0-9_.\']+)\s+where\s*$')
line_comment_re = re.compile(r'^\s*--\s*(.+)$')

rows: list[tuple[str, str, str, str]] = []

for path in sorted((ROOT / 'LogOS').rglob('*.agda')):
  if '_build' in path.parts:
    continue

  rel = path.relative_to(ROOT)
  module_name = '.'.join(rel.with_suffix('').parts)
  if len(rel.parts) > 2:
    layer = rel.parts[1]
  elif len(rel.parts) == 2:
    layer = Path(rel.parts[1]).stem
  else:
    layer = '-'

  text = path.read_text(encoding='utf-8')
  lines = text.splitlines()

  spec = '-'
  for line in lines:
    m = spec_re.match(line)
    if m:
      spec = m.group(1).strip()
      break

  summary = '-'
  saw_module = False
  for line in lines:
    if not saw_module and module_re.match(line):
      saw_module = True
      continue
    if not saw_module:
      continue

    if line.strip() == '':
      continue

    cm = line_comment_re.match(line)
    if cm:
      comment = cm.group(1).strip()
      if comment and not comment.startswith('SpecRef:'):
        summary = comment
        break

  rows.append((module_name, layer, spec, summary))

with OUT.open('w', encoding='utf-8') as f:
  f.write('<!--\n')
  f.write('LogOS: a host-minimal Agda library for modular dynamic logic systems synthesized by AI\n')
  f.write('Copyright (C) 2026 AI.IMPACT GmbH\n')
  f.write('SPDX-License-Identifier: GPL-3.0-only\n')
  f.write('-->\n\n')
  f.write('# Module Index (Generated)\n\n')
  f.write('Generated by `scripts/gen/write_module_index.sh`.\n\n')
  f.write('| Module | Layer | SpecRef | Summary |\n')
  f.write('| --- | --- | --- | --- |\n')
  for module_name, layer, spec, summary in rows:
    safe_summary = summary.replace('|', '\\|').replace('`', "'")
    safe_spec = spec.replace('|', '\\|').replace('`', "'")
    f.write(f'| `{module_name}` | `{layer}` | `{safe_spec}` | {safe_summary} |\n')

try:
  shown = str(OUT.relative_to(ROOT))
except ValueError:
  shown = str(OUT)
print(f'write-module-index: wrote {shown}')
PY
