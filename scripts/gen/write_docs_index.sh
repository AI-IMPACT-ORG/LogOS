OUT_PATH="${OUT_PATH}" python3 -B - <<'PY'
from __future__ import annotations

import os
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(".").resolve()
OUT = (ROOT / Path(os.environ["OUT_PATH"])).resolve()
DEFAULT_OUT_REL = "docs/Generated/Docs_Index.md"

TITLE_RE = re.compile(r"^\s*(#|%)\s+(.*)$")
TRAILING_ANCHOR_RE = re.compile(r"\s*\{#.*\}\s*$")


def extract_title(path: Path) -> str:
    if path.suffix == ".tex":
        return path.name

    try:
        text = path.read_text(encoding="utf-8", errors="ignore")
    except OSError:
        return path.name

    for line in text.splitlines():
        m = TITLE_RE.match(line)
        if not m:
            continue
        title = m.group(2).strip()
        title = TRAILING_ANCHOR_RE.sub("", title).strip()
        if title:
            return title
    return path.name


def kind_for(path: Path) -> str:
    if path.name.endswith(".lagda.md"):
        return "typechecked"
    if "docs/Generated" in path.as_posix():
        return "generated"
    return "plain"


def iter_docs() -> list[Path]:
    docs_dir = ROOT / "docs"
    files: list[Path] = []
    for p in docs_dir.rglob("*"):
        if "_build" in p.parts:
            continue
        if not p.is_file():
            continue
        if p.name.endswith(".lagda.md") or p.suffix in {".md", ".tex"}:
            files.append(p)
    files.sort()
    return files


def rel_md_link(path: Path) -> str:
    default_out_dir = (ROOT / Path(DEFAULT_OUT_REL)).resolve().parent
    rel = os.path.relpath(path, start=default_out_dir)
    return Path(rel).as_posix()


def main() -> None:
    entries: list[tuple[str, str, str, str]] = []
    for p in iter_docs():
        rel = p.relative_to(ROOT).as_posix()
        # Avoid self-listing to keep diffs stable and avoid circularity.
        # Important: compare to the canonical output path, not OUT (which varies
        # under freshness checks that generate into a tmpdir).
        if rel == DEFAULT_OUT_REL:
            continue
        title = extract_title(p)
        kind = kind_for(p)

        parts = rel.split("/")
        if len(parts) == 2 and parts[1] == "README.md":
            group = "Hub"
            subgroup = "-"
        else:
            group = parts[1] if len(parts) > 1 else "docs"
            subgroup = parts[2] if len(parts) > 3 else "-"

        entries.append((group, subgroup, title, rel))

    # Deterministic grouping.
    grouped: dict[tuple[str, str], list[tuple[str, str]]] = defaultdict(list)
    for group, subgroup, title, rel in entries:
        grouped[(group, subgroup)].append((title, rel))
    for k in grouped:
        grouped[k].sort(key=lambda x: x[1])

    group_order = ["Hub", "Core", "Results", "Patterns", "Interpretations", "Generated"]
    subgroup_orders: dict[str, list[str]] = {
        "Hub": ["-"],
        "Core": ["-", "Orientation", "Architecture", "Spec", "Policy", "Meta", "MetaTheory", "Textbook", "Project"],
        "Results": ["-"],
        "Patterns": ["-", "HowTo", "Clarifications", "Examples"],
        "Interpretations": ["-", "Orientation", "Paths", "Views", "Applications"],
        "Generated": ["-"],
    }

    def group_key(g: str) -> tuple[int, str]:
        try:
            return (group_order.index(g), g)
        except ValueError:
            return (999, g)

    def subgroup_key(g: str, sg: str) -> tuple[int, str]:
        order = subgroup_orders.get(g, [])
        try:
            return (order.index(sg), sg)
        except ValueError:
            return (999, sg)

    with OUT.open("w", encoding="utf-8") as f:
        f.write("<!--\n")
        f.write("LogOS: a host-minimal Agda library for modular dynamic logic systems synthesized by AI\n")
        f.write("Copyright (C) 2026 AI.IMPACT GmbH\n")
        f.write("SPDX-License-Identifier: GPL-3.0-only\n")
        f.write("-->\n\n")
        f.write("# Docs Index (Generated)\n\n")
        f.write("Generated by `scripts/gen/write_docs_index.sh`.\n\n")
        f.write("Legend:\n\n")
        f.write("- **typechecked**: `*.lagda.md` (checked by `scripts/check_all_docs.sh`)\n")
        f.write("- **plain**: `*.md` / `*.tex`\n")
        f.write("- **generated**: committed generated docs under `docs/Generated/**`\n\n")

        for g in sorted({k[0] for k in grouped.keys()}, key=group_key):
            f.write(f"## {g}\n\n")
            sgs = [sg for (gg, sg) in grouped.keys() if gg == g]
            for sg in sorted(set(sgs), key=lambda s: subgroup_key(g, s)):
                items = grouped.get((g, sg), [])
                if not items:
                    continue
                if sg != "-":
                    f.write(f"### {sg}\n\n")
                for title, rel in items:
                    path = (ROOT / rel)
                    k = kind_for(path)
                    f.write(f"- [{title}]({rel_md_link(path)}) — {k}\n")
                f.write("\n")

    try:
        shown = str(OUT.relative_to(ROOT))
    except ValueError:
        shown = str(OUT)
    print(f"write-docs-index: wrote {shown}")


if __name__ == "__main__":
    main()
PY
