source "${SCRIPT_DIR}/lib/check_common.sh"

ROOT="$(check_repo_root "${BASH_SOURCE[0]}")"
cd "${ROOT}"

OUT_PATH="${1:-docs/Generated/Published_Surface_Index.md}"
OUT_DIR="$(dirname "${OUT_PATH}")"
mkdir -p "${OUT_DIR}"

OUT_PATH="${OUT_PATH}" python3 -B - <<'PY'
from __future__ import annotations

import os
import sys
from pathlib import Path

ROOT = Path(".").resolve()
OUT = (ROOT / Path(os.environ["OUT_PATH"])).resolve()
MANIFEST = ROOT / "scripts" / "publication_surface.tsv"
ALLOWLIST = ROOT / "scripts" / "publication_default_lane_allowlist.tsv"

TIER_LABELS = {
    "published": "Published",
    "internal": "Shipped But Internal",
    "archive": "Archived / Out Of Contract",
}
TIER_ORDER = ["published", "internal", "archive"]


def load_tsv(path: Path, expected_cols: int) -> list[list[str]]:
    if not path.is_file():
        print(f"write-published-surface-index: missing TSV: {path.relative_to(ROOT).as_posix()}", file=sys.stderr)
        raise SystemExit(1)
    rows: list[list[str]] = []
    for i, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        cols = [part.strip() for part in raw.split("\t")]
        if len(cols) != expected_cols or any(not col for col in cols):
            print(
                f"{path.relative_to(ROOT).as_posix()}:{i}: expected {expected_cols} non-empty tab-separated columns",
                file=sys.stderr,
            )
            raise SystemExit(1)
        rows.append(cols)
    return rows


entries = load_tsv(MANIFEST, 4)
allowlist = load_tsv(ALLOWLIST, 2)

with OUT.open("w", encoding="utf-8") as f:
    f.write("<!--\n")
    f.write("LogOS: a host-minimal Agda library for modular dynamic logic systems synthesized by AI\n")
    f.write("Copyright (C) 2026 AI.IMPACT GmbH\n")
    f.write("SPDX-License-Identifier: GPL-3.0-only\n")
    f.write("-->\n\n")
    f.write("# Published Surface Index (Generated)\n\n")
    f.write("Generated by `scripts/gen/write_published_surface_index.sh` from explicit publication manifests.\n\n")
    f.write("This index records which subtrees are presented as public entrypoints, which are shipped as internal implementation layers, and which remain historical or optional.\n\n")

    for tier in TIER_ORDER:
        f.write(f"## {TIER_LABELS[tier]}\n\n")
        tier_entries = sorted((e for e in entries if e[0] == tier), key=lambda e: e[2])
        if not tier_entries:
            f.write("- None.\n\n")
            continue
        for _, kind, path, note in tier_entries:
            f.write(f"- `{path}` ({kind}) — {note}\n")
        f.write("\n")

    f.write("## Default-Lane Strictification Exceptions\n\n")
    f.write("These modules remain on an explicit shrinking allowlist because they still depend on quarantined bookkeeping transport in ways not yet eliminated from the public implementation story.\n\n")
    for module_name, justification in sorted(allowlist, key=lambda e: e[0]):
        f.write(f"- `{module_name}` — {justification}\n")
    f.write("\n")

try:
    shown = str(OUT.relative_to(ROOT))
except ValueError:
    shown = str(OUT)
print(f"write-published-surface-index: wrote {shown}")
PY
