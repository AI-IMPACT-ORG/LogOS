from __future__ import annotations

import os
import re
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(".").resolve()
OUT = (ROOT / Path(os.environ["OUT_PATH"])).resolve()

STAMP_RE = re.compile(
    r"^\s*<!--\s*CLAIM-STAMP:\s*(DEFINITION|DERIVED|ASSUMPTION|ANALOGY|PLANNED)\s*\|\s*anchor=([^ >]+)\s*-->\s*$"
)
HEADING_RE = re.compile(r"^\s*(#|%)\s+(.*)$")
TRAILING_ANCHOR_RE = re.compile(r"\s*\{#.*\}\s*$")


def iter_docs() -> list[Path]:
    docs_dir = ROOT / "docs"
    files: list[Path] = []
    for p in docs_dir.rglob("*"):
        if "_build" in p.parts:
            continue
        if not p.is_file():
            continue
        if p.name.endswith(".lagda.md") or p.suffix == ".md":
            files.append(p)
    files.sort()
    return files


def heading_after(lines: list[str], start: int) -> str:
    for i in range(start + 1, min(len(lines), start + 60)):
        m = HEADING_RE.match(lines[i])
        if not m:
            continue
        title = m.group(2).strip()
        title = TRAILING_ANCHOR_RE.sub("", title).strip()
        if title:
            return title
    return "-"


def main() -> None:
    rows: list[tuple[str, str, str, str]] = []

    for path in iter_docs():
        rel = path.relative_to(ROOT).as_posix()
        try:
            text = path.read_text(encoding="utf-8")
        except OSError:
            continue
        lines = text.splitlines()
        for idx, line in enumerate(lines):
            m = STAMP_RE.match(line)
            if not m:
                continue
            kind = m.group(1)
            anchor = m.group(2).strip()
            ctx = heading_after(lines, idx)
            rows.append((kind, rel, anchor, ctx))

    kind_order = ["DEFINITION", "DERIVED", "ASSUMPTION", "ANALOGY", "PLANNED"]

    rows.sort(
        key=lambda r: (
            kind_order.index(r[0]) if r[0] in kind_order else 999,
            r[1],
            r[2],
        )
    )

    counts = Counter(r[0] for r in rows)
    total = sum(counts.values())

    grouped: dict[str, list[tuple[str, str, str]]] = defaultdict(list)
    for kind, rel, anchor, ctx in rows:
        grouped[kind].append((rel, anchor, ctx))

    with OUT.open("w", encoding="utf-8") as f:
        f.write("<!--\n")
        f.write("LogOS: a host-minimal Agda library for modular dynamic logic systems synthesized by AI\n")
        f.write("Copyright (C) 2026 AI.IMPACT GmbH\n")
        f.write("SPDX-License-Identifier: GPL-3.0-only\n")
        f.write("-->\n\n")
        f.write("# Claim Stamp Index (Generated)\n\n")
        f.write("Generated by `scripts/gen/write_claim_stamp_index.sh`.\n\n")
        f.write("This index enumerates every `CLAIM-STAMP` under `docs/**` as a navigation surface for audits.\n\n")
        f.write("## Summary\n\n")
        f.write(f"- Total stamps: **{total}**\n")
        for k in kind_order:
            f.write(f"- {k}: **{counts.get(k, 0)}**\n")
        f.write("\n")

        for kind in kind_order:
            items = grouped.get(kind, [])
            if not items:
                continue
            f.write(f"## {kind}\n\n")
            f.write("| Source | Anchor | Context |\n")
            f.write("| --- | --- | --- |\n")
            for rel, anchor, ctx in items:
                src_link = f"`{rel}`"
                safe_anchor = anchor.replace("|", "\\|")
                safe_ctx = ctx.replace("|", "\\|")
                f.write(f"| {src_link} | `{safe_anchor}` | {safe_ctx} |\n")
            f.write("\n")

    try:
        shown = str(OUT.relative_to(ROOT))
    except ValueError:
        shown = str(OUT)
    print(f"write-claim-stamp-index: wrote {shown}")


if __name__ == "__main__":
    main()
PY

