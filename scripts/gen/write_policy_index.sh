OUT_PATH="${OUT_PATH}" python3 -B - <<'PY'
from __future__ import annotations

import os
import re
import importlib.util
import sys
from pathlib import Path

ROOT = Path(".").resolve()
OUT = (ROOT / Path(os.environ["OUT_PATH"])).resolve()
SCRIPTS_DIR = ROOT / "scripts"
CHECK_SCRIPTS_DIR = SCRIPTS_DIR / "check"

CHECK_NAME_RE = re.compile(r'^\s*CHECK_NAME\s*=\s*["\']([^"\']+)["\']\s*$')
POLICY_STRING_RE = re.compile(r'["\']Policy:\s*([^"\']+?)["\']')


def extract_check_name(text: str, fallback: str) -> str:
    for line in text.splitlines():
        m = CHECK_NAME_RE.match(line)
        if m:
            return m.group(1).strip()
    return fallback


def extract_policy(text: str) -> str:
    lines = text.splitlines()
    for i, line in enumerate(lines):
        stripped = line.lstrip()
        if not stripped.startswith("#"):
            continue
        if "Policy:" not in stripped:
            continue

        after = stripped.split("Policy:", 1)[1].strip()
        policy_lines: list[str] = []
        if after:
            policy_lines.append(after)

        for j in range(i + 1, len(lines)):
            s = lines[j].lstrip()
            if not s.startswith("#"):
                break
            # Drop leading '# ' if present.
            content = s[1:]
            if content.startswith(" "):
                content = content[1:]
            if content.strip() == "":
                if policy_lines:
                    break
                continue
            # Skip boilerplate comments that don't help in the index.
            if content.startswith("shellcheck "):
                continue
            policy_lines.append(content.rstrip())

        return "\n".join(policy_lines).strip()

    m = POLICY_STRING_RE.search(text)
    if m:
        return m.group(1).strip()

    return "(Policy not annotated in script comments or error messages.)"

def extract_agda_policy_bundle_policies() -> list[tuple[str, str]]:
    bundle_path = ROOT / "scripts" / "lib" / "agda_policy_bundle.py"
    if not bundle_path.is_file():
        return []

    spec = importlib.util.spec_from_file_location("agda_policy_bundle", bundle_path)
    if spec is None or spec.loader is None:
        return []

    mod = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = mod
    spec.loader.exec_module(mod)

    checks = getattr(mod, "CHECKS", None)
    if not isinstance(checks, list):
        return []

    out: list[tuple[str, str]] = []
    for c in checks:
        name = getattr(c, "name", None)
        policy = getattr(c, "policy", None)
        if isinstance(name, str) and isinstance(policy, str):
            out.append((name, policy.strip()))
    return out


def main() -> None:
    scripts = sorted(CHECK_SCRIPTS_DIR.glob("*_check.sh"))
    rows: list[tuple[str, str, str]] = []

    for path in scripts:
        text = path.read_text(encoding="utf-8")
        check_name = extract_check_name(text, fallback=path.stem.replace("_", "-"))
        policy = extract_policy(text)

        if check_name == "agda-policy-bundle-check":
            subs = extract_agda_policy_bundle_policies()
            if subs:
                lines: list[str] = []
                lines.append(policy.strip())
                lines.append("Subchecks (use `bash scripts/check/agda_policy_bundle_check.sh --only <name>`):")
                for name, pol in subs:
                    lines.append(f"`{name}`: {pol}")
                policy = "\n".join(lines)

        rows.append((check_name, path.relative_to(ROOT).as_posix(), policy))

    rows.sort(key=lambda r: r[0])

    with OUT.open("w", encoding="utf-8") as f:
        f.write("<!--\n")
        f.write("LogOS: a host-minimal Agda library for modular dynamic logic systems synthesized by AI\n")
        f.write("Copyright (C) 2026 AI.IMPACT GmbH\n")
        f.write("SPDX-License-Identifier: GPL-3.0-only\n")
        f.write("-->\n\n")
        f.write("# Policy Index (Generated)\n\n")
        f.write("Generated by `scripts/gen/write_policy_index.sh` from `scripts/check/*_check.sh`.\n\n")
        f.write("This is the human-readable index of the `make ci-policy` checks.\n\n")

        for check_name, rel, policy in rows:
            f.write(f"## `{check_name}`\n\n")
            f.write(f"- Script: `{rel}`\n")
            f.write(f"- Run: `make {check_name}`\n")
            f.write("- Policy:\n\n")
            for line in policy.splitlines():
                normalized = line.strip()
                if normalized.startswith(("- ", "* ")):
                    normalized = normalized[2:].strip()
                f.write(f"  - {normalized}\n")
            f.write("\n")

    try:
        shown = str(OUT.relative_to(ROOT))
    except ValueError:
        shown = str(OUT)
    print(f"write-policy-index: wrote {shown}")


if __name__ == "__main__":
    main()
PY
