SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# shellcheck source=scripts/lib/check_common.sh
source "${SCRIPT_DIR}/lib/check_common.sh"

ROOT="$(check_repo_root "${BASH_SOURCE[0]}")"
cd "${ROOT}"

OUT_PATH="${1:-docs/Interpretations/Views/All.lagda.md}"
OUT_DIR="$(dirname "${OUT_PATH}")"
mkdir -p "${OUT_DIR}"

OUT_PATH="${OUT_PATH}" python3 -B - <<'PY'
from __future__ import annotations

import os
import re
from pathlib import Path

ROOT = Path(".").resolve()
OUT = (ROOT / Path(os.environ["OUT_PATH"])).resolve()
VIEWS_DIR = ROOT / "docs" / "Interpretations" / "Views"

TITLE_RE = re.compile(r"^\s*(#|%)\s+(.*)$")
TRAILING_ANCHOR_RE = re.compile(r"\s*\{#.*\}\s*$")


def title_of(path: Path) -> str:
    text = path.read_text(encoding="utf-8")
    for line in text.splitlines():
        m = TITLE_RE.match(line)
        if not m:
            continue
        title = TRAILING_ANCHOR_RE.sub("", m.group(2).strip()).strip()
        if title:
            return title
    return path.name


def module_of(path: Path) -> str:
    rel = path.relative_to(ROOT).as_posix()
    return rel.removesuffix(".lagda.md").replace("/", ".")


docs = sorted(
    p for p in VIEWS_DIR.glob("*.lagda.md") if p.name != "All.lagda.md"
)

with OUT.open("w", encoding="utf-8") as f:
    f.write("<!--\n")
    f.write("LogOS: a host-minimal Agda library for modular dynamic logic systems synthesized by AI\n")
    f.write("Copyright (C) 2026 AI.IMPACT GmbH\n")
    f.write("SPDX-License-Identifier: GPL-3.0-only\n")
    f.write("-->\n\n")
    f.write("% Views -- LogOS (generated imports)\n\n")
    f.write("```agda\n")
    f.write("{-# OPTIONS --safe #-}\n")
    f.write("module docs.Interpretations.Views.All where\n\n")
    f.write("import LogOS.API.LT\n")
    for path in docs:
        stem = path.stem.split(".")[0]
        f.write(f"import {module_of(path)} as {stem}\n")
    f.write("```\n\n")
    f.write("Generated by `scripts/gen/write_views_all.sh`.\n\n")
    f.write("This file imports every umbrella view note under `docs/Interpretations/Views/**`.\n\n")
    f.write("Included view families:\n\n")
    for path in docs:
        rel = path.relative_to(ROOT).as_posix()
        f.write(f"- {title_of(path)}: `{rel}`\n")

try:
    shown = str(OUT.relative_to(ROOT))
except ValueError:
    shown = str(OUT)
print(f"write-views-all: wrote {shown}")
PY
